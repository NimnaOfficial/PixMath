"""AST-to-GLSL transpiler for PixMath math expressions.

Converts a **validated** Python :class:`ast.Expression` tree (produced by
:func:`app.sandbox.validate`) into a complete ``#version 330 core`` GLSL
fragment shader.  The generated shader:

* Declares ``uniform float u_time`` and ``uniform vec2 u_resolution``.
* Maps ``gl_FragCoord`` to normalised coordinates in **[-1, 1]**.
* Inlines safe-math wrappers (``safe_div``, ``safe_sqrt``, etc.) to avoid
  GPU-side undefined behaviour.
* Maps Python math identifiers to their GLSL equivalents.

Typical usage::

    from app.sandbox import validate
    from app.transpiler import transpile

    tree = validate("sin(x * pi) + cos(y * tau)")
    glsl_source = transpile(tree)
"""
from __future__ import annotations

import ast
from typing import Final

# ---------------------------------------------------------------------------
# Constant mappings
# ---------------------------------------------------------------------------

#: Python constant names → GLSL literal values.
_CONST_MAP: Final[dict[str, str]] = {
    "pi": "3.14159265358979",
    "e": "2.71828182845905",
    "tau": "6.28318530717959",
}

#: Python function names → GLSL function names.
_FUNC_MAP: Final[dict[str, str]] = {
    "sin": "sin",
    "cos": "cos",
    "tan": "tan",
    "asin": "asin",
    "acos": "acos",
    "atan": "atan",
    "atan2": "atan",          # GLSL atan(y, x) overload
    "exp": "exp",
    "log": "safe_log",
    "log2": "safe_log2",
    "log10": "safe_log10",
    "sqrt": "safe_sqrt",
    "abs": "abs",
    "min": "min",
    "max": "max",
    "clamp": "clamp",
    "floor": "floor",
    "ceil": "ceil",
    "fract": "fract",
    "sign": "sign",
    "step": "step",
    "smoothstep": "smoothstep",
    "mix": "mix",
    "mod": "mod",
    "noise": "noise",
    "length": "length",
}

#: Python binary operator → GLSL infix token.
_BINOP_MAP: Final[dict[type, str]] = {
    ast.Add: "+",
    ast.Sub: "-",
    ast.Mult: "*",
    ast.Div: "/",
    ast.Mod: "%",              # mapped to mod() call in special handling
    ast.FloorDiv: "/",         # requires floor() wrapper
}

#: Python comparison operator → GLSL infix token.
_CMPOP_MAP: Final[dict[type, str]] = {
    ast.Eq: "==",
    ast.NotEq: "!=",
    ast.Lt: "<",
    ast.LtE: "<=",
    ast.Gt: ">",
    ast.GtE: ">=",
}

# ---------------------------------------------------------------------------
# Shader template pieces
# ---------------------------------------------------------------------------

_SHADER_VERSION: Final[str] = "#version 330 core"

_SHADER_HEADER: Final[str] = """\
#version 330 core

// ── PixMath generated fragment shader ──────────────────────────────────
// Auto-generated by the PixMath AST-to-GLSL transpiler.  Do not edit.

uniform float u_time;
uniform vec2  u_resolution;

out vec4 fragColor;

// ── Safe math helpers ──────────────────────────────────────────────────

float safe_div(float a, float b) {
    return (abs(b) < 1e-7) ? 0.0 : a / b;
}

float safe_sqrt(float v) {
    return sqrt(max(v, 0.0));
}

float safe_pow(float base, float ex) {
    return (base < 0.0) ? -pow(-base, ex) : pow(base, ex);
}

float safe_log(float v) {
    return log(max(v, 1e-7));
}

float safe_log2(float v) {
    return log2(max(v, 1e-7));
}

float safe_log10(float v) {
    return safe_log(v) / safe_log(10.0);
}

// Simple value-noise (deterministic, GPU-friendly)
float _hash(vec2 p) {
    return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453123);
}

float noise(float v) {
    float i = floor(v);
    float f = fract(v);
    return mix(_hash(vec2(i, 0.0)), _hash(vec2(i + 1.0, 0.0)), f);
}

float length(float v) {
    return abs(v);
}

"""

_SHADER_MAIN_PREFIX: Final[str] = """\
void main() {
    // Map pixel coordinates to [-1, 1] range.
    vec2 uv = (gl_FragCoord.xy / u_resolution.xy) * 2.0 - 1.0;
    float x = uv.x;
    float y = uv.y;
    float t = u_time;

    // ── Evaluate expression ────────────────────────────────────────────
    float value = """

_SHADER_MAIN_SUFFIX: Final[str] = """\
;

    // Clamp for colour output.
    float c = clamp(value, 0.0, 1.0);
    fragColor = vec4(c, c, c, 1.0);
}
"""


# ---------------------------------------------------------------------------
# Transpiler
# ---------------------------------------------------------------------------

class GLSLTranspiler(ast.NodeVisitor):
    """Walk a validated Python AST and emit a GLSL expression string.

    This visitor produces **only** the inner expression (the part that goes
    into ``float value = <…>;``).  The surrounding shader boilerplate is
    assembled by :func:`transpile`.
    """

    # -- visitor entry point -------------------------------------------------

    def transpile_expression(self, tree: ast.Expression) -> str:
        """Return the GLSL expression string for *tree*.

        Parameters:
            tree: A validated :class:`ast.Expression` AST.

        Returns:
            A GLSL expression string (no trailing semicolon).
        """
        return self.visit(tree.body)

    # -- visitors ------------------------------------------------------------

    def visit_Constant(self, node: ast.Constant) -> str:  # noqa: N802
        """Emit a numeric literal."""
        value = node.value
        if isinstance(value, float):
            return f"{value}"
        if isinstance(value, int):
            return f"{float(value)}"
        # Should never reach here if the validator did its job.
        return str(value)  # pragma: no cover

    def visit_Name(self, node: ast.Name) -> str:  # noqa: N802
        """Emit a variable reference or constant substitution."""
        if node.id in _CONST_MAP:
            return _CONST_MAP[node.id]
        return node.id

    def visit_UnaryOp(self, node: ast.UnaryOp) -> str:  # noqa: N802
        """Emit a unary operation."""
        operand = self.visit(node.operand)
        if isinstance(node.op, ast.USub):
            return f"(-{operand})"
        if isinstance(node.op, ast.UAdd):
            return f"(+{operand})"
        return operand  # pragma: no cover

    def visit_BinOp(self, node: ast.BinOp) -> str:  # noqa: N802
        """Emit a binary operation with safe wrappers where needed."""
        left = self.visit(node.left)
        right = self.visit(node.right)

        # Power → safe_pow
        if isinstance(node.op, ast.Pow):
            return f"safe_pow({left}, {right})"

        # Division → safe_div
        if isinstance(node.op, ast.Div):
            return f"safe_div({left}, {right})"

        # Floor division → floor(safe_div(…))
        if isinstance(node.op, ast.FloorDiv):
            return f"floor(safe_div({left}, {right}))"

        # Modulo → mod(…)
        if isinstance(node.op, ast.Mod):
            return f"mod({left}, {right})"

        op_str = _BINOP_MAP.get(type(node.op), "+")
        return f"({left} {op_str} {right})"

    def visit_Call(self, node: ast.Call) -> str:  # noqa: N802
        """Emit a function call mapped to GLSL."""
        # node.func is guaranteed to be ast.Name by the validator.
        func_name: str = node.func.id  # type: ignore[attr-defined]
        glsl_name = _FUNC_MAP.get(func_name, func_name)

        args = ", ".join(self.visit(arg) for arg in node.args)
        return f"{glsl_name}({args})"

    def visit_Compare(self, node: ast.Compare) -> str:  # noqa: N802
        """Emit a comparison (single comparator only).

        Chained comparisons (``a < b < c``) are reduced to
        ``(a < b) && (b < c)`` for GLSL compatibility.
        """
        parts: list[str] = []
        left = self.visit(node.left)
        for op, comparator in zip(node.ops, node.comparators):
            right = self.visit(comparator)
            op_str = _CMPOP_MAP.get(type(op), "==")
            parts.append(f"({left} {op_str} {right})")
            left = right

        if len(parts) == 1:
            return parts[0]
        joined = " && ".join(parts)
        return f"({joined})"

    def visit_BoolOp(self, node: ast.BoolOp) -> str:  # noqa: N802
        """Emit a boolean operation (and / or)."""
        glsl_op = "&&" if isinstance(node.op, ast.And) else "||"
        parts = [self.visit(v) for v in node.values]
        joined = f" {glsl_op} ".join(parts)
        return f"({joined})"

    def visit_IfExp(self, node: ast.IfExp) -> str:  # noqa: N802
        """Emit a ternary expression ``cond ? then : else``."""
        cond = self.visit(node.test)
        then = self.visit(node.body)
        else_ = self.visit(node.orelse)
        return f"(({cond}) ? {then} : {else_})"


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def transpile(expr: ast.Expression | str) -> str:
    """Convert a validated Python AST or math expression string into a complete GLSL fragment shader.

    Parameters:
        expr: A validated :class:`ast.Expression` or expression string.

    Returns:
        A ``#version 330 core`` GLSL fragment shader source string ready
        to be compiled and rendered.
    """
    if isinstance(expr, str):
        from app.sandbox.ast_validator import validate
        expr_ast = validate(expr)
    else:
        expr_ast = expr

    transpiler = GLSLTranspiler()
    glsl_expr = transpiler.transpile_expression(expr_ast)
    return f"{_SHADER_HEADER}{_SHADER_MAIN_PREFIX}{glsl_expr}{_SHADER_MAIN_SUFFIX}"

